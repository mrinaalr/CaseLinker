"""Who sent a CyberTip, when the release says so (#20).

Every person and place here is made up. The sentence shapes are the ones the
corpus uses (case ids in comments are where each shape was read).
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
for sub in ("src", "src/Processing Layer"):
    if str(ROOT / sub) not in sys.path:
        sys.path.insert(0, str(ROOT / sub))

import processing  # noqa: E402

P = processing.assertions_module.patterns
R = processing.assertions_module.resolution


def _found(text):
    return sorted({(a["role"], a["value"]) for a in P.cybertip_reporter_assertions(text)})


@pytest.mark.parametrize("text, expected", [
    # doj_safe_childhood_2024_108
    ("Wren Halloway was caught after the social media app Kik submitted a CyberTip to the "
     "National Center for Missing and Exploited Children.", [("named_esp", "Kik")]),
    # ncmec_2022_016
    ("The case originated from a cyber tip sent by Microsoft to the National Center for "
     "Missing and Exploited Children in late 2021.", [("named_esp", "Microsoft")]),
    # ncmec_2024_973
    ("The detective received six CyberTip Line reports from Google between May and June.",
     [("named_esp", "Google")]),
    # ncmec_2022_029
    ("Police said NCMEC received a cyber tip from Facebook/Meta Platforms, Inc. in March.",
     [("named_esp", "Facebook")]),
    # azicac_2011_009: the reporter is in the next sentence
    ("Agents searched a home as the result of a cybertip police received from the National "
     "Center for Missing and Exploited Children. AOL had discovered an e-mail with an image.",
     [("named_esp", "AOL")]),
    # ncmec_2025_742: quoted affidavit
    ("She was notified of a CyberTip from NCMEC: “Snapchat reported that an individual had "
     "uploaded apparent child sexual abuse material.”", [("named_esp", "Snapchat")]),
    # doj_safe_childhood_2025_322: a list after a category
    ("Officers alerted agents to CyberTipline reports related to abuse material from several online "
     "social media and messaging platforms including Google, Tumblr and Discord.",
     [("named_esp", "Discord"), ("named_esp", "Google"), ("named_esp", "Tumblr")]),
    # ncmec_2025_1022: appositive
    ("Police received a Cyber tip report, which stated that the Electronic Service Provider, "
     "Dropbox, reported two files to NCMEC.", [("named_esp", "Dropbox")]),
])
def test_named_reporter(text, expected):
    assert _found(text) == expected



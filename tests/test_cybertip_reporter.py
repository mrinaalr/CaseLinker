def test_no_reporter(text):
    assert _found(text) == []


def test_reporter_resolves_only_for_a_case_scoped_tip():
    no_tip = R.resolve_cybertip_reporter([], {"final_value": []})
    assert no_tip["status"] == "empty" and no_tip["final_value"] is None

    tip = {"final_value": ["cybertip"]}
    unstated = R.resolve_cybertip_reporter([], tip)
    assert unstated["final_value"] == {"kind": "unstated", "esps": [], "category": None}

    rows = [
        {"field": "cybertip_reporter", "value": "social_media", "role": "category", "span_ok": True, "method": "regex"},
        {"field": "cybertip_reporter", "value": "Kik", "role": "named_esp", "span_ok": True, "method": "regex"},
        {"field": "cybertip_reporter", "value": "Google", "role": "named_esp", "span_ok": False, "method": "regex"},
    ]
    named = R.resolve_cybertip_reporter(rows, tip)
    assert named["final_value"] == {"kind": "esp", "esps": ["Kik"], "category": None}
    assert named["rule_id"] == "named_esp"


def test_every_reporter_assertion_passes_the_span_gate():
    """No span, no value: the stored row must keep its span, or resolution ignores it."""
    gate = processing.assertions_module.gate_assertion
    text = ("Police received a CyberTip from the social media platform Kik. Agents also reviewed "
            "a cyber tip sent by Microsoft. A cybertip from a cloud storage provider followed.")
    rows = [gate(text, a) for a in P.cybertip_reporter_assertions(text)]
    assert rows and all(r["span_ok"] for r in rows), rows
    assert not gate(text, {**rows[0], "value": "Google"})["span_ok"]

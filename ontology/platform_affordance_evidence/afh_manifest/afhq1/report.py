"""Render outputs/TABLES.md from the JSON outputs. Every number here is read, not typed."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

CLASSES = ("Anonymity", "Ephemerality", "ContactDiscovery", "UnmonitoredCommunication",
           "DistributionInfrastructure", "GenerativeSynthesis")


def _t(headers: List[str], rows: List[List[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def write(out: Path) -> Path:
    j = lambda n: json.loads((out / n).read_text(encoding="utf-8"))  # noqa: E731
    inv, june, cov, tmp, rec, harm, man, leg, val = (j(n) for n in (
        "inventory.json", "june_2026_reconciliation.json", "affordance_coverage.json", "temporal.json",
        "recurrence.json", "harm.json", "manifest.json", "legacy_afh1_exemplars.json", "validation.json"))
    d = inv["denominators"]
    md = ["# AfH 2.0 Q1 tables", "",
          "Generated by `ontology/platform_affordance_evidence/afh_manifest/run_all.py`. Snapshot and code identity: `RUN_IDENTITY.json`.", ""]

    an = inv["tiers"]["analysed_for_affordances"]
    md += ["## How to read each table", "",
           _t(["Table", "Denominator", "Unit", "Generic labels included?", "Classes overlap?", "Describes"], [
               ["A inventory, broad row", f"{d['corpus_cases']:,} corpus cases", "distinct cases and platform-case observations", "yes", "n/a", "platform presence and documented use (tiers)"],
               ["A inventory, strict row", f"{d['strict_eligible_cases']:,} strict cases", "distinct cases and platform-case observations", "no", "n/a", "platform presence and documented use (tiers)"],
               ["B affordance coverage", f"{an['cases']:,} assessed cases (specific + Gen AI + alias labels)", "distinct cases (observations in brackets)", "no (Gen AI and alias labels yes)", "yes: a case can count in several classes", "A capability availability; B, I, C documented conduct at increasing strictness"],
               ["C eras / annual", "cases published in that year or era", "distinct cases", "strict columns: no", "class columns overlap", "presence, documented use, A to C per class"],
               ["D recurrence", "cases at that level in the class", "distinct cases; families and eras with 2+ cases", "no (Gen AI and alias yes)", "yes", "spread of each level"],
               ["E affordance x harm", "cases at that level in the class", "distinct cases", "no (Gen AI and alias yes)", "yes, classes and harms both", "documented harm co-occurring with a level; psi(a) pathways are potential"],
               ["F manifest", "cases naming that platform", "distinct cases per platform", "Gen AI and alias rows included and marked", "yes", "A to C per class for one platform"],
               ["Tier variants", f"{d['strict_eligible_cases']:,} strict cases", "distinct cases (records in tier_variants.json)", "no", "n/a", "documented use under each tier rule"],
           ]), "",
           (f"Why some class counts exceed the {d['strict_eligible_cases']:,} strict cases: the affordance tables are computed on "
            f"{an['cases']:,} assessed cases, the strict cases plus {d['technology_only_cases_no_specific_platform']} cases whose only analysed label is "
            f"Gen AI and {d['ambiguous_alias_only_cases']} whose only analysed label is an ambiguous alias (Webcam platform, Mega). "
            "Classes overlap, so summing across classes exceeds any case total. Level A counts availability: a capability "
            "present on the platform in the publication year, not use."), ""]
    md += ["## A. Corpus inventory", "", _t(["Measure", "Value"], [[k, v] for k, v in d.items()]), ""]
    md += ["Tiers (case = best record tier; mutually exclusive):", "",
           _t(["Eligibility", "cases", "stated", "inferred only", "named only", "records", "labels"],
              [[k, t["cases"], t["cases_stated"], t["cases_inferred"], t["cases_named_only"], t["records"], t["labels"]]
               for k, t in inv["tiers"].items()]), ""]
    md += ["Reconciliation checks: " + ", ".join(f"{k}={v}" for k, v in inv["reconciliation"].items()), ""]
    md += ["Exclusions (pairs / distinct cases): " + ", ".join(
        f"{k} {v} / {inv['exclusions']['distinct_cases'][k]}" for k, v in inv["exclusions"]["platform_case_pairs"].items()), ""]
    md += ["AfH 1.0 (June 2026) as committed:", "",
           _t(["candidates", "pairs", "labels", "with records", "stated", "inferred only", "named only", "non-generic cand.", "specific-only cand."],
              [[june["candidate_cases"], june["platform_case_pairs"], june["labels"], june["cases_with_records"], june["stated"],
                june["inferred_only"], june["named_only"], june["candidate_cases_non_generic"], june["candidate_cases_specific_only"]]]),
           "", june["note"], ""]

    LV = ["A_available_capability", "B_capability_relevant_conduct", "I_inferred_facilitation", "C_explicit_instrumental_use"]
    md += ["## B. Affordance coverage (specific + technology + alias labels)", "",
           "Levels nest: A available capability > B documented capability-relevant conduct > I analytically inferred facilitation > C explicit instrumental use. Distinct cases (platform-case observations).", "",
           _t(["Class"] + ["A", "B", "I", "C"] + ["C labels", "C families", "review candidates"],
              [[c] + [f"{v[l]['distinct_cases']} ({v[l]['platform_case_observations']})" for l in LV] +
               [v[LV[3]]["distinct_platform_labels"], v[LV[3]]["platform_families"], sum(v["review_candidates"].values())]
               for c, v in cov["classes"].items()]), "", cov["reading"], "",
           f"Named platforms only (the paper's {cov['analytic_sets']['named_platforms']['cases']:,}-case analytic set):", "",
           _t(["Class", "A", "B", "I", "C"],
              [[c] + [f"{v[l]['distinct_cases']} ({v[l]['platform_case_observations']})" for l in LV]
               for c, v in cov["classes_named_platforms_only"].items()]), ""]

    md += ["## C. Publication-year eras", "", "Publication year, not offense year. Strict = specific named platform.", ""]
    cols = ["cases", "sources", "ncmec_cases", "strict_named_platform_cases", "strict_use_documented_cases",
            "pct_strict_named", "pct_use_documented_of_named", "distinct_platforms_use_documented"]
    for title, block in (("All sources", tmp["eras"]), ("Excluding NCMEC", tmp["eras_excluding_ncmec"])):
        md += [f"**{title}**", "", _t(["era"] + cols + [f"{c}.C" for c in CLASSES],
                                      [[e] + [r[k] for k in cols] + [r[f"{c}.C"] for c in CLASSES] for e, r in block.items()]), ""]
    md += ["**Within DOJ Safe Childhood (annual)**", "",
           _t(["year"] + cols, [[y] + [r[k] for k in cols] for y, r in tmp["within_source_annual"]["DOJ SAFE CHILDHOOD"].items()]), ""]
    md += ["**Annual, all sources**", "",
           _t(["year"] + cols, [[y] + [r[k] for k in cols] for y, r in tmp["annual"].items()]), ""]

    md += ["## D. Recurrence", "", rec["rule"], "",
           _t(["Class"] + [f"{l.split('_')[0]} cases / families / eras" for l in LV] + ["recurs at"],
              [[c] + [f"{r[l]['cases']} / {r[l]['families_with_2plus_cases']} / {r[l]['eras_with_2plus_cases']}" for l in LV] +
               [", ".join(l.split("_")[0] for l in LV if r["recurs_across_families_and_eras"][l]) or "none"]
               for c, r in rec["classes"].items()]), "", rec["reading"], ""]
    harms = ["h1_groomed_toward_in_person", "h2_coerced_self_generated", "h3_material_distributed", "h4_sextorted", "h6_likeness_synthesized"]
    md += ["## E. Affordance x harm", "", harm["caution"], "", harm["shared_trigger_warning"], "",
           "Documented harm (direct / case-level) by class and level; * marks a potential pathway in AfH psi(a).", ""]
    for l in LV[1:]:
        md += [f"**{l}**", "", _t(["Class", "cases"] + harms,
               [[c, v[l]["of_cases"]] + [f"{v[l][h]['documented_direct']} / {v[l][h]['documented_case_level']}{'*' if v[l][h]['potential_per_afh_psi'] else ''}" for h in harms]
                for c, v in harm["by_class_and_level"].items()]), ""]
    md += ["AfH psi(a) pathways:", "", _t(["Class", "Harm", "pathway open (B cases)", "doc. case-level | B", "doc. direct | B", "| I", "| C", "label"],
           [[c, h, v["potential_pathway_cases_B"], v["documented_case_level_given_B"], v["documented_direct_given_B"], v["documented_direct_given_I"], v["documented_direct_given_C"], v["label"]]
            for c, hs in harm["afh1_psi_pathways"].items() for h, v in hs.items()]), ""]

    md += ["## F. Manifest", "", f"Platforms with at least {man['min_use_documented_cases']} use-documented cases. Citation check: {man['citation_check']}", "",
           _t(["Platform", "family", "cases", "use-documented", "years", "capabilities (since)"] + [f"{c[:6]} A/B/I/C" for c in CLASSES],
              [[p, e["family"], e["cases"], e["use_documented_cases"], "-".join(map(str, e["pub_year_range_use_documented"])),
                ", ".join(f"{k} {v['since'] if isinstance(v, dict) else v}" for k, v in e["capability_profile"].items())] +
               ["/".join(str(e["classes"][c][x]) for x in "ABIC") for c in CLASSES]
               for p, e in sorted(man["platforms"].items(), key=lambda kv: -kv[1]["use_documented_cases"])]), ""]

    md += ["## G. AfH 1.0 harm-vector exemplars", "", f"{leg['citations']} citations: {leg['tally']}", ""]

    md += ["## Validation", "", f"{val['reviewed_rows']} reviewed rows; fingerprints changed since review: {val['rows_with_changed_fingerprint']}", "",
           _t(["item", "n", "verdicts", "precision / share", "95% Wilson"],
              [[k, v["n"], v["verdicts"], v.get("precision", v.get("share_actually_documenting_use", "")), v.get("wilson95", "")]
               for k, v in val["by_item"].items()]), "",
           f"C rows after codebook-2: {val['C_rows_under_current_codebook']}", ""]
    v2 = j("validation_round2.json")
    cs = v2["classification_sample"]
    md += ["## Validation, round 2 (independent blind reviewer + adjudication)", "",
           "Reviewer agreement on the 107-row sample (binary: claim holds):", "",
           _t(["item group", "n", "agree", "kappa"], [[k, v["n"], v["agree"], v["kappa"]] for k, v in cs["agreement"].items()]), "",
           "After adjudication:", "",
           _t(["item", "n", "holds", "95% Wilson"], [[k, v["n"], v["holds"], v["wilson95"]] for k, v in cs["adjudicated"].items()]), "",
           "Evidence tiers (new 70-row sample, blind):", "",
           _t(["published tier", "n", "use documented", "share", "95% Wilson"],
              [[k, v["n"], v["use"], v["share_use"], v["wilson95"]] for k, v in v2["tier_sample"]["by_published_tier"].items()]), "",
           "Named-only rows by the rule that kept them there: " + "; ".join(f"{g} {c}" for g, c in v2["tier_sample"]["named_only_by_gate"].items()), "",
           "Sensitivity tier vs reviewer (named-only rows): " + str(v2["tier_sample"]["sensitivity_tier_vs_reviewer_named_only"]), "",
           "Strict use-documented cases: " + ", ".join(f"{k} {v}" for k, v in v2["use_documented_strict_cases"].items() if k != "note"), "",
           "Harm cues (74-row blind sample): share the reviewer judged documented and tied to the platform:", "",
           _t(["harm | group", "n", "share", "95% Wilson"],
              [[k, v["n"], v["share_documented_with_platform"], v["wilson95"]] for k, v in v2["harm_sample"]["by_harm_and_group"].items()]), ""]
    if v2["inferred_sample"]["rows"]:
        md += ["Inferred facilitation (I, not C), blind plausibility check:", "",
               _t(["class", "n", "reasonable", "weak", "not reasonable", "share reasonable", "95% Wilson"],
                  [[k, v["n"], v.get("reasonable_inference", 0), v.get("weak_inference", 0), v.get("not_reasonable", 0), v["share_reasonable"], v["wilson95"]]
                   for k, v in v2["inferred_sample"]["by_class"].items()]), ""]
    path = out / "TABLES.md"
    path.write_text("\n".join(md) + "\n", encoding="utf-8")
    return path

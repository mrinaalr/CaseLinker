"""LaTeX (booktabs) tables for AfH 2.0, rendered from outputs/*.json. Numbers are read, never typed.

Each table is a standalone `tabular` in outputs/latex/ for \\input{} into the manuscript; the
caption and label belong to the manuscript. Requires \\usepackage{booktabs}.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, List

CLASSES = ("Anonymity", "Ephemerality", "ContactDiscovery", "UnmonitoredCommunication",
           "DistributionInfrastructure", "GenerativeSynthesis")
CLASS_TEX = {"Anonymity": "Anonymity", "Ephemerality": "Ephemerality", "ContactDiscovery": "Contact discovery",
             "UnmonitoredCommunication": "Unmonitored communication",
             "DistributionInfrastructure": "Distribution infrastructure", "GenerativeSynthesis": "Generative synthesis"}
LV = ("A_available_capability", "B_capability_relevant_conduct", "I_inferred_facilitation", "C_explicit_instrumental_use")
_ESC = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}"}


def esc(v: Any) -> str:
    s = "" if v is None else str(v)
    return "".join(_ESC.get(ch, ch) for ch in s)


def num(v: Any) -> str:
    return f"{v:,}" if isinstance(v, int) else esc(v)


def tabular(cols: str, header: List[str], rows: List[List[Any]], note: str = "") -> str:
    out = [f"% generated by research/afh_q1/afhq1/latex.py; do not edit", f"\\begin{{tabular}}{{{cols}}}", "\\toprule",
           " & ".join(header) + r" \\", "\\midrule"]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += ["\\bottomrule", "\\end{tabular}"]
    if note:
        out.insert(0, f"% {note}")
    return "\n".join(out) + "\n"


def write(out: Path) -> List[Path]:
    j = lambda n: json.loads((out / n).read_text(encoding="utf-8"))  # noqa: E731
    inv, cov, rec, man, tv, ex = (j(n) for n in ("inventory.json", "affordance_coverage.json", "recurrence.json",
                                                 "manifest.json", "tier_variants.json", "exemplar_inventory.json"))
    d = inv["denominators"]
    dest = out / "latex"
    dest.mkdir(exist_ok=True)
    paths = []

    def put(name: str, text: str):
        p = dest / name
        p.write_text(text, encoding="utf-8")
        paths.append(p)

    s, b, lw = inv["tiers"]["strict"], inv["tiers"]["broad"], inv["tiers_linewrap_alternative"]["strict"]
    put("tab_inventory.tex", tabular("lrr", ["Measure", "Cases", "Platform--case observations"], [
        ["Corpus", num(d["corpus_cases"]), "--"],
        ["Any platform label (broad)", num(b["cases"]), num(b["records"])],
        ["Specific named platform (strict)", num(s["cases"]), num(s["records"])],
        [r"\quad stated (primary / baseline)", f"{num(lw['cases_stated'])} / {num(s['cases_stated'])}", f"{num(lw['records_stated'])} / {num(s['records_stated'])}"],
        [r"\quad inferred only (co-occurrence)", f"{num(lw['cases_inferred'])} / {num(s['cases_inferred'])}", f"{num(lw['records_inferred'])} / {num(s['records_inferred'])}"],
        [r"\quad named only", f"{num(lw['cases_named_only'])} / {num(s['cases_named_only'])}", f"{num(lw['records_named_only'])} / {num(s['records_named_only'])}"],
        [r"\textbf{Documented use, stated or co-occurring (primary: line-wrap repair)}", num(lw["cases_stated"] + lw["cases_inferred"]), num(lw["records_stated"] + lw["records_inferred"])],
        [r"Documented use (original-rule baseline)", num(s["cases_stated"] + s["cases_inferred"]), num(s["records_stated"] + s["records_inferred"])],
        ["Generic category only", num(d["generic_category_only_cases"]), "--"],
    ], note=f"{d['corpus_cases']} cases, {d['sources']} sources"))

    rows = []
    for c in CLASSES:
        v = cov["classes"][c]
        rows.append([CLASS_TEX[c]] + [num(v[l]["distinct_cases"]) for l in LV] +
                    [num(v[LV[3]]["distinct_platform_labels"])])
    put("tab_affordance_coverage.tex", tabular("lrrrrr", ["Affordance class", "Available", "Relevant conduct", "Inferred facilitation", "Explicit use", "Platforms (explicit)"], rows,
                                               note="distinct cases per evidence level; levels nest"))

    rows = []
    for c in CLASSES:
        r = rec["classes"][c]
        rows.append([CLASS_TEX[c]] + [f"{r[l]['cases']:,} / {r[l]['families_with_2plus_cases']} / {r[l]['eras_with_2plus_cases']}" for l in LV[1:]])
    put("tab_recurrence.tex", tabular("llll", ["Affordance class", "Relevant conduct", "Inferred facilitation", "Explicit use"], rows,
                                      note="cases / platform families with 2+ cases / publication eras with 2+ cases"))

    rows = []
    top = sorted(man["platforms"].items(), key=lambda kv: -kv[1]["use_documented_cases"])[:15]
    for p, e in top:
        caps = ", ".join(f"{CLASS_TEX[c].split()[0]} {e['capability_profile'][k]['since']}" for c, k in (
            ("Anonymity", "anonymity"), ("Ephemerality", "ephemerality"), ("ContactDiscovery", "contact_discovery"),
            ("UnmonitoredCommunication", "unmonitored_communication"), ("DistributionInfrastructure", "distribution_infrastructure"),
            ("GenerativeSynthesis", "generative_synthesis")) if k in e["capability_profile"])
        rows.append([esc(p), num(e["cases"]), num(e["use_documented_cases"]), esc(caps)])
    put("tab_platform_manifest.tex", tabular("lrrp{7cm}", ["Platform", "Cases", "Documented use", "Native capabilities (first year)"], rows,
                                             note="top 15 platforms by documented-use cases; full manifest in manifest.json"))

    v = tv["variants"]
    put("tab_tier_variants.tex", tabular("lr", ["Tier rule", "Documented-use cases"], [
        ["Original rules", num(v["A_original"]["use_documented_cases"])],
        ["Line-wrap repair, additive, boilerplate guard (primary)", num(v["Bplus_guarded"]["use_documented_cases"])],
        ["Line-wrap repair, additive, no guard", num(v["Bplus_unwrap_additive"]["use_documented_cases"])],
        ["Line-wrap repair, plain", num(v["B_unwrap"]["use_documented_cases"])],
        ["Expanded verbs only", num(v["C_verbs"]["use_documented_cases"])],
        ["Line-wrap + verbs", num(v["D_combined"]["use_documented_cases"])],
    ], note="strict cases"))

    rows = [[esc(r["platform"]), esc(r["cited_for"]), esc(r["case_id"]), esc(r["verdict"])]
            for r in ex["rows"] if r["verdict"] == "supported"]
    put("tab_verified_exemplars.tex", tabular("llll", ["Platform", "Cited for", "Case", "Review"], rows,
                                              note="exemplars a blind reviewer judged supported; case ids resolve through citations.json fingerprints"))
    return paths
